# Four basic data types. type() tells you the type of a value.

rotations = 12            # int: whole number
distance_cm = 45.5        # float: number with a decimal point
obstacle_seen = False     # bool: True or False
motor = "Motor A"         # str: text in quotation marks

print(type(rotations))
print(type(distance_cm))
print(type(obstacle_seen))
print(type(motor))
print(type("25"))         # predict first: number or text?
print(type(7 / 2))        # challenge: what type does division give?
