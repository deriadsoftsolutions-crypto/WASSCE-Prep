# Python's maths operators. Predict each answer, then run.

print(5 + 3)      # add
print(10 - 2)     # subtract
print(4 * 2)      # multiply
print(10 / 2)     # divide: always gives a decimal (float)
print(10 / 3)     # look at the last digit!
print(10 // 3)    # integer divide: whole number part only
print(10 % 3)     # modulo: the remainder
print(2 ** 3)     # power: 2 x 2 x 2
print("ab" + "cd")   # + joins text
print(7, "ab")       # a comma shows both side by side
